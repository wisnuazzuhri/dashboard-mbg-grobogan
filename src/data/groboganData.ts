// Helper calculations
export function calculateTotals(sppgList: SPPGUnit[]) {
  const totals = {
    totalSppg: sppgList.length,
    kapasitasTotal: 0,
    totalPM: 0,
    kelompok3B: {
      bumil: 0,
      busui: 0,
      balita: 0,
      total: 0,
    },
    jenjangPendidikan: {
      paudTkRa: 0,
      sdMi: 0,
      smpMts: 0,
      smaSmkMa: 0,
      slb: 0,
      pesantren: 0,
      seminari: 0,
      pkbm: 0,
      total: 0,
    },
  };

  sppgList.forEach(item => {
    totals.kapasitasTotal += item.kapasitasHarian;

    // 3B
    totals.kelompok3B.bumil += item.kelompok3B.bumil;
    totals.kelompok3B.busui += item.kelompok3B.busui;
    totals.kelompok3B.balita += item.kelompok3B.balita;

    // Pendidikan
    totals.jenjangPendidikan.paudTkRa += item.jenjangPendidikan.paudTkRa;
    totals.jenjangPendidikan.sdMi += item.jenjangPendidikan.sdMi;
    totals.jenjangPendidikan.smpMts += item.jenjangPendidikan.smpMts;
    totals.jenjangPendidikan.smaSmkMa += item.jenjangPendidikan.smaSmkMa;
    totals.jenjangPendidikan.slb += item.jenjangPendidikan.slb;
    totals.jenjangPendidikan.pesantren += item.jenjangPendidikan.pesantren;
    totals.jenjangPendidikan.seminari += item.jenjangPendidikan.seminari;
    totals.jenjangPendidikan.pkbm += item.jenjangPendidikan.pkbm;
  });

  totals.kelompok3B.total = totals.kelompok3B.bumil + totals.kelompok3B.busui + totals.kelompok3B.balita;
  totals.jenjangPendidikan.total =
    totals.jenjangPendidikan.paudTkRa +
    totals.jenjangPendidikan.sdMi +
    totals.jenjangPendidikan.smpMts +
    totals.jenjangPendidikan.smaSmkMa +
    totals.jenjangPendidikan.slb +
    totals.jenjangPendidikan.pesantren +
    totals.jenjangPendidikan.seminari +
    totals.jenjangPendidikan.pkbm;

  totals.totalPM = totals.kelompok3B.total + totals.jenjangPendidikan.total;

  return totals;
}
